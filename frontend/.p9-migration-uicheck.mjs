import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const p = await b.newPage();
let pass=0, fail=0;
const check=(n,c,d='')=>{if(c){pass++;console.log('PASS:',n,d);}else{fail++;console.log('FAIL:',n,d);}};
await p.goto('http://127.0.0.1:5173/#/login');
await p.waitForTimeout(800);
await p.fill('[data-testid="auth-email"]','teacher@local');
await p.fill('[data-testid="auth-password"]','Teacher123');
await p.click('[data-testid="auth-submit"]');
await p.waitForTimeout(1500);
check('migrated teacher signs in', p.url().includes('#/review'), p.url());
check('migration banner shown', await p.locator('[data-testid="migration-banner"]').isVisible());
await p.click('[data-testid="migration-confirm"]');
await p.waitForTimeout(400);
check('confirm opens My Space', await p.locator('[data-testid="my-space"]').isVisible());
check('banner text prefilled in profile', (await p.locator('[data-testid="profile-name"]').inputValue()) === 'My Space');
await p.fill('[data-testid="profile-name"]','Confirmed Teacher');
await p.fill('[data-testid="profile-email"]','confirmed@example.com');
await p.click('[data-testid="profile-save"]');
await p.waitForTimeout(700);
check('profile save updates top bar', (await p.locator('[data-testid="top-my-space"]').innerText()).includes('Confirmed Teacher'));
await p.goto('http://127.0.0.1:5173/#/library');
await p.waitForTimeout(1200);
check('banner gone after confirm', await p.locator('[data-testid="migration-banner"]').count() === 0);
const body = await p.locator('body').innerText();
check('legacy content visible after migration', body.includes('Mathematics') || body.includes('English'), body.slice(0,120));
console.log(`\n${pass}/${pass+fail} migration UI checks passed`);
await b.close();
if (fail) process.exit(1);

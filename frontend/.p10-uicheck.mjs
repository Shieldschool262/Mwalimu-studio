await p.fill('[data-testid="iep-review-date"]', d);
await p.click('[data-testid="iep-save"]');
await p.waitForTimeout(700);
check('IEP row created', (await p.locator('[data-testid="iep-row"]').count())===1);
await p.click('[data-testid="nav-dashboard"]');
await p.waitForTimeout(1200);
check('dashboard learner card', await p.locator('[data-testid="dash-learners-card"]').isVisible());
const card = await p.locator('[data-testid="dash-learners-card"]').innerText();
check('card counts active learner', card.includes('1 Active'), card);
await p.click('[data-testid="top-logout"]');

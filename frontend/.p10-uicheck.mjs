const stamp=Date.now();
import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const p = await b.newPage();
let pass=0, fail=0;
const check=(n,c,d='')=>{if(c){pass++;console.log('PASS:',n,d)}else{fail++;console.log('FAIL:',n,d)}};
await p.goto('http://127.0.0.1:5174/#/signup');
await p.waitForTimeout(700);
await p.fill('[data-testid="auth-name"]','Alice Teacher');
await p.fill('[data-testid="auth-email"]','`alice${stamp}@test.com`');
await p.fill('[data-testid="auth-password"]','Passw0rd');
await p.click('[data-testid="auth-submit"]');
await p.waitForTimeout(1000);
check('signup enters app', (await p.locator('[data-testid="nav-learners"]').count())===1, p.url());
await p.click('[data-testid="nav-learners"]');
await p.waitForTimeout(600);
check('My Learners route opens', p.url().includes('#/my-learners') && await p.locator('[data-testid="ml-root"]').isVisible());
check('empty state shown', await p.locator('[data-testid="ml-empty"]').isVisible());
await p.click('[data-testid="ml-add"]');
await p.fill('[data-testid="ml-first"]','Achieng');
await p.fill('[data-testid="ml-last"]','Otieno');
await p.fill('[data-testid="ml-class"]','3B');
await p.fill('[data-testid="ml-grade"]','Grade 3');
await p.fill('[data-testid="ml-area"]','Mathematics');
await p.click('[data-testid="ml-save"]');
await p.waitForTimeout(700);
check('learner row appears', (await p.locator('[data-testid="ml-learner-row"]').count())===1);
check('group title correct', (await p.locator('[data-testid="ml-group-title"]').innerText()).includes('3B (1 learners)'));
await p.click('[data-testid="ml-tab-progress"]');
await p.waitForTimeout(700);
check('progress view opens', await p.locator('[data-testid="progress-root"]').isVisible());
check('summary cards present', await p.locator('[data-testid="progress-summary"]').isVisible());

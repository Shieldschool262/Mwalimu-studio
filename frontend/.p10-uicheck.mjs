await p.fill('[data-testid="auth-password"]','Passw0rd');
await p.click('[data-testid="auth-submit"]');
await p.waitForTimeout(900);
await p.click('[data-testid="nav-learners"]');
await p.waitForTimeout(600);
check('second teacher sees empty list', await p.locator('[data-testid="ml-empty"]').isVisible());

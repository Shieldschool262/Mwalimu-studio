import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const p = await b.newPage();
let pass = 0, fail = 0;
const check = (n, c, d='') => { if (c) { pass++; console.log('PASS:', n, d); } else { fail++; console.log('FAIL:', n, d); } };
await p.goto('http://127.0.0.1:5173/#/dashboard');
await p.waitForTimeout(1500);
check('protected route redirects to login', p.url().includes('#/login') && p.url().includes('next='), p.url());
check('login form visible', await p.locator('[data-testid="auth-submit"]').isVisible());
await p.click('[data-testid="auth-submit"]'); // empty login -> generic 401 shown
await p.waitForTimeout(500);
check('invalid login shows generic message', (await p.locator('body').innerText()).includes('Invalid email or password'));
await p.goto('http://127.0.0.1:5173/#/signup');
await p.waitForTimeout(300);
await p.fill('[data-testid="auth-name"]', 'Mr. J. Kamau');
await p.fill('[data-testid="auth-email"]', 'ui@example.com');
await p.fill('[data-testid="auth-password"]', 'Passw0rd');
await p.click('[data-testid="auth-submit"]');
await p.waitForTimeout(1200);
check('signup enters app', !(await p.locator('body').innerText()).includes('Create your My Space'), p.url());
check('top bar shows My Space + name', (await p.locator('[data-testid="top-my-space"]').innerText()).includes('Mr. J. Kamau'));
await p.click('[data-testid="top-my-space"]');
await p.waitForTimeout(400);
check('My Space page opens', await p.locator('[data-testid="my-space"]').isVisible());
check('profile fields present', await p.locator('[data-testid="profile-tsc"]').count() === 1);
check('export all link present', await p.locator('[data-testid="export-all"]').count() === 1);
await p.goto('http://127.0.0.1:5173/#/dashboard');
await p.waitForTimeout(1200);
const title = await p.locator('[data-testid="dash-title"]').innerText().catch(()=>'');
check('dashboard title is individual', title.includes('My Coverage Dashboard') && title.includes('Mr. J. Kamau'), title);
await p.click('[data-testid="top-logout"]');
await p.waitForTimeout(1000);
check('logout returns to login', p.url().includes('#/login'), p.url());
console.log(`\n${pass}/${pass+fail} UI checks passed`);
await b.close();
if (fail) process.exit(1);
